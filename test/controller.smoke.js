import { Controller } from '../server/controller.js';
import { fkTcp } from '../shared/kinematics.js';
const c = new Controller();
c.setServo(true);
const p = c.tcpPose();
const t0 = performance.now();
await c.move({ kind: 'L', target: { pose: { p: [p.p[0], p.p[1] + 100, p.p[2] - 100], R: p.R } }, speed: { tcp: 250 } });
console.log('L move', ((performance.now() - t0) / 1000).toFixed(2), 's', c.tcpPose().p.map((v) => v.toFixed(2)));
await c.move({ kind: 'J', target: { joints: [30, 10, 10, 0, -60, 0] }, speed: { frac: 1 } });
console.log('J move ok', c.joints.map((v) => v.toFixed(2)));
const o = c.objects[0];
await c.move({ kind: 'J', target: { pose: { p: [o.pose.p[0], o.pose.p[1], o.pose.p[2] + 100], R: [[-1,0,0],[0,1,0],[0,0,-1]] } }, speed: { frac: 1 } });
await c.move({ kind: 'L', target: { pose: { p: [...o.pose.p], R: [[-1,0,0],[0,1,0],[0,0,-1]] } }, speed: { tcp: 500 } });
c.setDO(1, true);
await c.move({ kind: 'L', target: { pose: { p: [o.pose.p[0], o.pose.p[1], 200], R: [[-1,0,0],[0,1,0],[0,0,-1]] } }, speed: { tcp: 500 } });
console.log('holding', c.grip.holding?.id, 'obj z', o.pose.p[2].toFixed(1));
c.setDO(1, false);
console.log('dropped z', o.pose.p[2].toFixed(1));
process.exit(0);
